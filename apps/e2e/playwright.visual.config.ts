import { defineConfig, devices } from '@playwright/test';
import baseConfig from './playwright.config.ts';

/**
 * Playwright configuration for the Mi Cuenta visual-regression suite (HOS-2471,
 * HOS-2413 §6.11).
 *
 * WHY A SEPARATE CONFIG. A screenshot baseline only matches the browser and
 * the fonts that produced it. The baselines are generated inside the pinned
 * Playwright Docker image (`mcr.microsoft.com/playwright:v<version>-noble`,
 * the same version as `@playwright/test`), so the comparison must render in
 * that image too — never with the host's Chromium and fonts. This config keeps
 * the test RUNNER on the host (same Node, same `webServer` boot as the rest of
 * the suite) and connects to a browser served from the image by
 * `playwright run-server`. `scripts/run-visual.sh` starts that container and
 * passes its endpoint in `HOSPEDA_E2E_VISUAL_WS_ENDPOINT`.
 *
 * WHAT IT REUSES. Everything from `playwright.config.ts` except `projects`:
 * the same `webServer` triplet (production builds, never `astro dev`, which
 * breaks island hydration in Astro 7.4.7), the same reporters and modes.
 * The web server additionally gets `HOSPEDA_ACCOUNT_KIT_GALLERY=true` so the
 * gated kit gallery answers 200 — only when Playwright starts it. A reused
 * local server must have been started with that flag (see README).
 *
 * CI ONLY COMPARES (OD-7). `updateSnapshots` is `'none'` in CI: a missing or
 * different baseline fails the run and is never written. Baselines are
 * regenerated by hand with `e2e:visual:update` and committed in the same PR
 * as the UI change.
 */

const wsEndpoint = process.env.HOSPEDA_E2E_VISUAL_WS_ENDPOINT;
if (!wsEndpoint) {
    throw new Error(
        'playwright.visual.config.ts: HOSPEDA_E2E_VISUAL_WS_ENDPOINT is not set. ' +
            'Run the suite through `pnpm --filter hospeda-e2e e2e:test:visual`, which starts the ' +
            'pinned Playwright image and sets it. Rendering with the host browser would never ' +
            'match the committed baselines.'
    );
}

const isCI = (process.env.E2E_MODE ?? 'local') !== 'local';

/** The web server entry of the base config, with the kit gallery gate on. */
const webServers = (Array.isArray(baseConfig.webServer) ? baseConfig.webServer : []).map(
    (server) =>
        server.command.includes('hospeda-web')
            ? { ...server, env: { ...server.env, HOSPEDA_ACCOUNT_KIT_GALLERY: 'true' } }
            : server
);

export default defineConfig({
    ...baseConfig,
    testDir: './tests/visual',
    testMatch: /.*\.visual\.spec\.ts$/,
    // The visual specs only read seeded data, but one worker keeps the page
    // load (and therefore any lazy work) identical between runs.
    fullyParallel: false,
    workers: 1,
    // A retry would hide a flaky screenshot instead of exposing it.
    retries: 0,
    webServer: webServers,
    // Own report and output folders, so a CI job that ran the P0 suite first
    // keeps both reports (the P0 one lives in playwright-report/).
    reporter: isCI
        ? [
              ['html', { open: 'never', outputFolder: 'playwright-report-visual' }],
              ['github'],
              ['list']
          ]
        : [['html', { open: 'on-failure', outputFolder: 'playwright-report-visual' }], ['list']],
    outputDir: 'test-results-visual',
    snapshotPathTemplate: '{testDir}/__screenshots__/{testFileName}/{arg}{ext}',
    updateSnapshots: isCI ? 'none' : 'missing',
    expect: {
        timeout: 20_000,
        toHaveScreenshot: {
            // The repo's existing tolerance (SPEC-153). Measured: two
            // consecutive compare runs inside the pinned image passed all 306
            // shots, so no looser value is needed (HOS-2413 T-030 AC).
            maxDiffPixelRatio: 0.001,
            animations: 'disabled',
            caret: 'hide',
            scale: 'css'
        }
    },
    use: {
        ...baseConfig.use,
        // The browser is launched by the remote server, so the base config's
        // `launchOptions` (the HOS-1144 Cloudinary DNS block) travel in the
        // header `playwright run-server` reads its launch options from.
        connectOptions: {
            wsEndpoint,
            headers: {
                'x-playwright-launch-options': JSON.stringify(baseConfig.use?.launchOptions ?? {})
            }
        },
        locale: 'es-AR',
        timezoneId: 'America/Argentina/Buenos_Aires',
        trace: 'retain-on-failure',
        video: 'off'
    },
    projects: [
        {
            name: 'visual',
            use: { ...devices['Desktop Chrome'] }
        }
    ]
});
