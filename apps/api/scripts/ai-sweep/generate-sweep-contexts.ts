/**
 * Regenerates `packages/ai-core/scripts/ai-sweep/contexts.generated.json` (HOS-2095).
 *
 * Reads the sweep inputs (fixture cases, entity snapshots, catalog curation),
 * renders every case with the real production builders (see
 * `render-sweep-contexts.ts`) and writes the result. No network, no database.
 *
 * Run from the repo root after changing a builder, a default prompt/rule, an
 * input entity or a case's entity/feature/locale:
 *
 * ```bash
 * CI=true pnpm --filter hospeda-api exec tsx scripts/ai-sweep/generate-sweep-contexts.ts
 * ```
 *
 * `test/scripts/ai-sweep-contexts-parity.test.ts` fails while the committed file
 * is stale.
 *
 * @module apps/api/scripts/ai-sweep/generate-sweep-contexts
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { z } from 'zod';
import {
    CatalogCurationFileSchema,
    EntityFileSchema,
    mergeEntityFiles,
    RenderableCaseSchema,
    renderSweepCases
} from './render-sweep-contexts.js';

/** Directory of the sweep inside packages/ai-core. */
export const SWEEP_DIR = resolve(
    import.meta.dirname,
    '../../../../packages/ai-core/scripts/ai-sweep'
);

/** Note written at the top of the generated file. */
export const GENERATED_NOTE =
    'GENERATED by apps/api/scripts/ai-sweep/generate-sweep-contexts.ts. Do not edit by hand. ' +
    'Each context is the real builder output over inputs/*.json. The system message of a case is ' +
    'context + systemSuffixes[feature][locale], verified byte-identical to the real buildChatSystemMessage ' +
    'over the in-code DEFAULT_PROMPTS + DEFAULT_RULES.';

const readJson = (name: string): unknown =>
    JSON.parse(readFileSync(resolve(SWEEP_DIR, name), 'utf8'));

/**
 * Loads every input and renders the file content.
 *
 * @returns `{ json }`: the exact text the generated file must contain.
 */
export function buildGeneratedFile(): { readonly json: string } {
    const cases = z
        .object({ cases: z.array(RenderableCaseSchema.passthrough()) })
        .parse(readJson('fixtures.json')).cases;
    const { entities } = mergeEntityFiles({
        files: [
            EntityFileSchema.parse(readJson('inputs/accommodation-snapshots.json')),
            EntityFileSchema.parse(readJson('inputs/synthetic-entities.json'))
        ]
    });
    const curation = CatalogCurationFileSchema.parse(readJson('inputs/catalog-curation.json'));
    const rendered = renderSweepCases({ cases, entities, curation });
    return {
        json: `${JSON.stringify({ _note: GENERATED_NOTE, systemSuffixes: rendered.suffixes, cases: rendered.cases }, null, 4)}\n`
    };
}

if (process.argv[1] && resolve(process.argv[1]) === resolve(import.meta.filename)) {
    const { json } = buildGeneratedFile();
    const target = resolve(SWEEP_DIR, 'contexts.generated.json');
    writeFileSync(target, json);
    console.log(`Wrote ${target}`);
}
