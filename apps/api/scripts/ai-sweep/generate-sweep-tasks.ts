/**
 * Regenerates `packages/ai-core/scripts/ai-sweep/tasks.generated.json` (HOS-2217).
 *
 * Reads every `task-fixtures/<feature>.json`, renders each case's provider
 * request with the real production builders (see `render-sweep-tasks.ts`) and
 * serializes the output schemas with the AI SDK's own conversion. No network,
 * no database.
 *
 * Run from the repo root after changing a fixture input, a route builder, an
 * output schema or an entity of `inputs/*.json`:
 *
 * ```bash
 * CI=true pnpm --filter hospeda-api exec tsx scripts/ai-sweep/generate-sweep-tasks.ts
 * ```
 *
 * `test/scripts/ai-sweep-tasks-parity.test.ts` fails while the committed file
 * is stale.
 *
 * @module apps/api/scripts/ai-sweep/generate-sweep-tasks
 */

import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import {
    digestInput,
    TaskFixtureFileSchema
} from '../../../../packages/ai-core/scripts/ai-sweep/tasks.js';
import { SWEEP_DIR } from './generate-sweep-contexts.js';
import {
    CatalogCurationFileSchema,
    EntityFileSchema,
    mergeEntityFiles
} from './render-sweep-contexts.js';
import { renderOutputSchemas, renderTask } from './render-sweep-tasks.js';

/** Note written at the top of the generated file. */
export const GENERATED_TASKS_NOTE =
    'GENERATED by apps/api/scripts/ai-sweep/generate-sweep-tasks.ts. Do not edit by hand. ' +
    'Each request is the real route builder output over task-fixtures/*.json; each schema is the ' +
    'AI SDK zodSchema() conversion of the production Zod output schema.';

const readJson = (name: string): unknown =>
    JSON.parse(readFileSync(resolve(SWEEP_DIR, name), 'utf8'));

/**
 * Loads every fixture and renders the file content.
 *
 * @returns `{ json }`: the exact text the generated file must contain.
 */
export function buildGeneratedTasksFile(): { readonly json: string } {
    const { entities } = mergeEntityFiles({
        files: [
            EntityFileSchema.parse(readJson('inputs/accommodation-snapshots.json')),
            EntityFileSchema.parse(readJson('inputs/synthetic-entities.json'))
        ]
    });
    const curation = CatalogCurationFileSchema.parse(readJson('inputs/catalog-curation.json'));
    const files = readdirSync(resolve(SWEEP_DIR, 'task-fixtures'))
        .filter((f) => f.endsWith('.json'))
        .sort();
    const cases: Record<string, unknown> = {};
    for (const file of files) {
        for (const c of TaskFixtureFileSchema.parse(readJson(`task-fixtures/${file}`)).cases) {
            if (c.id in cases) throw new Error(`Duplicated task case id "${c.id}".`);
            const { rendered } = renderTask({ call: c.call, input: c.input, entities, curation });
            cases[c.id] = { call: c.call, inputDigest: digestInput(c.input).digest, ...rendered };
        }
    }
    const { schemas } = renderOutputSchemas();
    return {
        json: `${JSON.stringify({ _note: GENERATED_TASKS_NOTE, schemas, cases }, null, 4)}\n`
    };
}

if (process.argv[1] && resolve(process.argv[1]) === resolve(import.meta.filename)) {
    const { json } = buildGeneratedTasksFile();
    const target = resolve(SWEEP_DIR, 'tasks.generated.json');
    writeFileSync(target, json);
    console.log(`Wrote ${target}`);
}
