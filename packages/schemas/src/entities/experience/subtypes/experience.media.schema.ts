// ----------------------------------------------------------------------------
// Reorder Input Schema
// ----------------------------------------------------------------------------

/**
 * HTTP payload schema for `PATCH /:id/media/reorder`.
 * The caller supplies the full ordered list of visible media UUIDs; the
 * service validates that this set matches the current visible rows exactly
 * and then applies the new `sortOrder` positions.
 */
export const ExperienceMediaReorderPayloadSchema = z.object({
    /**
     * Ordered array of `experience_media` UUIDs.
     * Must contain exactly the same IDs as the current visible rows — no
     * extras, no missing entries. The service rejects any mismatch with
     * `VALIDATION_ERROR`.
     */
    orderedIds: z
        .array(z.string().uuid({ message: 'zodError.common.id.invalidUuid' }), {
            message: 'zodError.experience.media.reorder.orderedIds.invalid'
        })
        .min(1, { message: 'zodError.experience.media.reorder.orderedIds.min' })
});

/** Inferred type for the reorder payload. */
export type ExperienceMediaReorderPayload = z.infer<typeof ExperienceMediaReorderPayloadSchema>;

/**
 * Service input schema for reordering an experience listing's gallery.
 * Combines the URL param `experienceId` with the ordered-ids payload.
 */
export const ExperienceMediaReorderInputSchema = z.object({
    /** UUID of the parent experience listing (from URL param `/:id`). */
    experienceId: z.string().uuid({ message: 'zodError.common.id.invalidUuid' }),
    /** Ordered array of visible media UUIDs. */
    orderedIds: ExperienceMediaReorderPayloadSchema.shape.orderedIds
});

/** Inferred type for the reorder service input. */
export type ExperienceMediaReorderInput = z.infer<typeof ExperienceMediaReorderInputSchema>;

