// ----------------------------------------------------------------------------
// Set Featured Input Schema
// ----------------------------------------------------------------------------

/**
 * Service input schema for setting the featured photo of an experience listing.
 *
 * Targets a specific `experience_media` row by ID and promotes it to
 * `is_featured = true`. The previous featured row (if any) is cleared in the
 * same transaction.
 *
 * DB invariants enforced (extras carril, mirroring accommodation's T-003):
 * - At most ONE featured row per listing (partial unique index).
 * - A featured photo can never be `state = 'archived'` (CHECK constraint).
 * The service validates that the target row is `state = 'visible'` before
 * writing to avoid tripping the CHECK constraint.
 */
export const ExperienceMediaSetFeaturedInputSchema = z.object({
    /** UUID of the parent experience listing (from URL param `/:id`). */
    experienceId: z.string().uuid({ message: 'zodError.common.id.invalidUuid' }),
    /** UUID of the media row to promote as featured (from URL param `/:mediaId`). */
    mediaId: z.string().uuid({ message: 'zodError.common.id.invalidUuid' })
});

/** Inferred type for the set-featured service input. */
export type ExperienceMediaSetFeaturedInput = z.infer<typeof ExperienceMediaSetFeaturedInputSchema>;

// ----------------------------------------------------------------------------
// Archive Photo Input Schema
// ----------------------------------------------------------------------------

/**
 * Service input schema for archiving a single experience photo.
 *
 * Flips `state = 'archived'` and sets `archivedAt = NOW()` on the target row.
 * A FEATURED photo cannot be archived — the DB CHECK constraint enforces
 * `NOT (is_featured AND state = 'archived')`. The service rejects the request
 * before reaching the DB when `isFeatured = true`.
 */
export const ExperienceMediaArchiveInputSchema = z.object({
    /** UUID of the parent experience listing (from URL param `/:id`). */
    experienceId: z.string().uuid({ message: 'zodError.common.id.invalidUuid' }),
    /** UUID of the media row to archive (from URL param `/:mediaId`). */
    mediaId: z.string().uuid({ message: 'zodError.common.id.invalidUuid' })
});

/** Inferred type for the archive-media service input. */
export type ExperienceMediaArchiveInput = z.infer<typeof ExperienceMediaArchiveInputSchema>;

// ----------------------------------------------------------------------------
// Restore Photo Input Schema
// ----------------------------------------------------------------------------

/**
 * Service input schema for restoring an archived experience photo.
 *
 * Flips `state = 'visible'`, clears `archivedAt = NULL`, and appends the row
 * at the END of the current visible gallery (`sortOrder = max visible + 1`).
 */
export const ExperienceMediaRestoreInputSchema = z.object({
    /** UUID of the parent experience listing (from URL param `/:id`). */
    experienceId: z.string().uuid({ message: 'zodError.common.id.invalidUuid' }),
    /** UUID of the archived media row to restore (from URL param `/:mediaId`). */
    mediaId: z.string().uuid({ message: 'zodError.common.id.invalidUuid' })
});

/** Inferred type for the restore-media service input. */
export type ExperienceMediaRestoreInput = z.infer<typeof ExperienceMediaRestoreInputSchema>;
