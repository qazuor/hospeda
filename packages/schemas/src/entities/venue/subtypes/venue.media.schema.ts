/**
 * Input payload for adding a single photo to a gastronomy listing gallery.
 *
 * This is a URL-receiver schema: the upload to Cloudinary has already
 * happened via `POST /api/v1/admin/media/upload`. This endpoint registers
 * the already-uploaded URL as a new `gastronomy_media` row.
 *
 * Server-controlled fields are intentionally EXCLUDED from the input:
 * - `id`            — generated by the DB
 * - `gastronomyId`  — comes from the URL param `/:id`
 * - `sortOrder`     — computed as max(visible sortOrder) + 1 (append to end)
 * - `isFeatured`    — never client-settable. This payload always produces a
 *                     gallery row; the cover is created by the dedicated
 *                     featured endpoint, which decides it server-side
 *                     (HOS-803).
 * - `state`         — always `'visible'` on create
 * - `archivedAt`    — null on create (set when archiving)
 * - Audit timestamps — set by the DB
 */
export const VenueMediaAddPayloadSchema = z.object({
    /**
     * Full public URL of the photo (Cloudinary delivery URL or external CDN).
     * Required — the upload endpoint returns this URL before this call is made.
     */
    url: mediaAssetUrl('zodError.common.listingMedia.url.invalid'),
    /**
     * Cloudinary `public_id` (e.g. `hospeda/dev/abc123`).
     * Optional — historic or external-URL payloads may not carry one.
     */
    publicId: z
        .string()
        .min(1, { message: 'zodError.common.listingMedia.publicId.min' })
        .optional(),
    /**
     * Short display caption (max 100 chars).
     * Optional — not all photos include a caption.
     */
    caption: z
        .string()
        .min(3, { message: 'zodError.common.listingMedia.caption.min' })
        .max(100, { message: 'zodError.common.listingMedia.caption.max' })
        .optional(),
    /**
     * Longer description of photo content (max 300 chars).
     * Optional.
     */
    description: z
        .string()
        .min(10, { message: 'zodError.common.listingMedia.description.min' })
        .max(300, { message: 'zodError.common.listingMedia.description.max' })
        .optional(),
    /**
     * Accessible alt text for `<img alt>` and screen readers.
     * Optional; falls back to caption / listing name at render time.
     */
    alt: z
        .string()
        .min(1, { message: 'zodError.common.listingMedia.alt.min' })
        .max(200, { message: 'zodError.common.listingMedia.alt.max' })
        .optional(),
    /**
     * Optional credits/source metadata (photographer, sourceUrl, license).
     */
    attribution: ImageAttributionSchema.nullable().optional(),
    /**
     * Content moderation state supplied by the upload endpoint.
     * When omitted the service defaults to `'PENDING'`.
     * Upload endpoint pre-approves images, so callers should pass `'APPROVED'`.
     */
    moderationState: ModerationStatusEnumSchema.optional()
});

/** Inferred type for the add-media payload. */
export type VenueMediaAddPayload = z.infer<typeof VenueMediaAddPayloadSchema>;

